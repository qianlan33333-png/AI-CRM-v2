type Tier string

const (
	TierS Tier = "s"
	TierM Tier = "m"
	TierL Tier = "l"
)

type QueueConcurrency struct {
	Critical int
	Event    int
	Outbound int
	Sync     int
	Heavy    int
	AI       int
}

func (queues QueueConcurrency) Total() int {
	return queues.Critical + queues.Event + queues.Outbound + queues.Sync + queues.Heavy + queues.AI
}

