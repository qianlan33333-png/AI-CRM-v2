func Lookup(value string) (Config, error) {
	config, ok := configs[Tier(value)]
	if !ok {
		return Config{}, ErrInvalidTier
	}
	if config.WorkerPoolMaxConns < config.Queues.Total()+2 {
		return Config{}, ErrInvalidTier
	}
	return config, nil
}

