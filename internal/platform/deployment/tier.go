func Generate(config Config, outputDirectory string) error {
	directory, err := prepareOutputDirectory(outputDirectory)
	if err != nil {
		return err
	}
	if err := writeAtomic(directory, PostgreSQLFileName, config.RenderPostgreSQL()); err != nil {
		return err
	}
	return writeAtomic(directory, EnvironmentFileName, config.RenderEnvironment())
}

func prepareOutputDirectory(value string) (string, error) {
	if value == "" || strings.TrimSpace(value) != value {
		return "", ErrUnsafeOutputPath
	}
	absolute, err := filepath.Abs(value)
	if err != nil || absolute == string(filepath.Separator) {
		return "", ErrUnsafeOutputPath
	}
	absolute, err = canonicalOutputPath(absolute)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(absolute, 0o750); err != nil {
		return "", fmt.Errorf("create deployment output: %w", err)
	}
	if err := os.Chmod(absolute, 0o750); err != nil {
		return "", fmt.Errorf("secure deployment output: %w", err)
	}
	return absolute, nil
}

func canonicalOutputPath(absolute string) (string, error) {
	if info, err := os.Lstat(absolute); err == nil {
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return "", ErrUnsafeOutputPath
		}
		resolved, err := filepath.EvalSymlinks(absolute)
		if err != nil {
			return "", ErrUnsafeOutputPath
		}
		return resolved, nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return "", ErrUnsafeOutputPath
	}

	ancestor := absolute
	var missing []string
	for {
		missing = append([]string{filepath.Base(ancestor)}, missing...)
		ancestor = filepath.Dir(ancestor)
		info, err := os.Lstat(ancestor)
		if err == nil {
			if !info.IsDir() && info.Mode()&os.ModeSymlink == 0 {
				return "", ErrUnsafeOutputPath
			}
			resolved, err := filepath.EvalSymlinks(ancestor)
			if err != nil {
				return "", ErrUnsafeOutputPath
			}
			return filepath.Join(append([]string{resolved}, missing...)...), nil
		}
		if !errors.Is(err, os.ErrNotExist) || ancestor == filepath.Dir(ancestor) {
			return "", ErrUnsafeOutputPath
		}
	}
}

func writeAtomic(directory, name, content string) error {
	target := filepath.Join(directory, name)
	if info, err := os.Lstat(target); err == nil {
		if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
			return ErrUnsafeOutputPath
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("inspect deployment output: %w", err)
	}

	temporary, err := os.CreateTemp(directory, ".aicrm-config-*")
	if err != nil {
		return fmt.Errorf("create deployment output: %w", err)
	}
	temporaryName := temporary.Name()
	defer os.Remove(temporaryName)
	if err := temporary.Chmod(0o640); err != nil {
		temporary.Close()
		return fmt.Errorf("secure deployment output: %w", err)
	}
	if _, err := io.WriteString(temporary, content); err != nil {
		temporary.Close()
		return fmt.Errorf("write deployment output: %w", err)
	}
	if err := temporary.Sync(); err != nil {
		temporary.Close()
		return fmt.Errorf("sync deployment output: %w", err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close deployment output: %w", err)
	}
	if err := os.Rename(temporaryName, target); err != nil {
		return fmt.Errorf("publish deployment output: %w", err)
	}
	return nil
}
